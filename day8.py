# ---------- return 和 print 的区别（今天最重要的知识点）----------
#
#   print  → 只是【显示给人看】，函数的值是 None
#   return → 把结果【交回给调用者】，可以存进变量、继续计算
#
#   例子 A（错）：
#       def avg_bad(s):
#           print(sum(s) / len(s))
#       x = avg_bad([1,2,3])      # 屏幕显示 2.0，但 x 是 None ！
#
#   例子 B（对）：
#       def avg_good(s):
#           return sum(s) / len(s)
#       x = avg_good([1,2,3])     # x = 2.0，可以接着用
#
#   口诀：【要给别人用就 return，只是给人看就 print】


