scores = []

print("=== 成绩册 4.0（函数版）===")
print("输入成绩，直接回车结束\n")

while True:
    s = input("成绩：")
    if s == "":
        break
    try:
        score = float(s)
    except ValueError:
        print("那不是数字，再输一次")
        continue
    scores.append(score)

if len(scores) == 0:
    print("没有录入任何成绩")
    exit()


def average(scores):
    if len(scores)==0:
        return 0
    elif len(scores)==1:
        return scores[0]
    return (sum(scores)-max(scores))/(len(scores)-1)
def grade(score):
    if score>=90:
        return "优秀"
    elif score>=80:
        return "良好"
    elif score>=70:
        return "中等"
    elif score>=60:
        return "及格"
    else:
        return "不及格"
x = average(scores)
print(f"平均分：{x:.2f}等级：{grade(x)}")

