# ---------- 别忘了 ----------
# 运行前先按 Ctrl + C 确认没有旧程序还在等输入
# （昨晚那个教训：清屏不杀进程，改文件也不影响已经在跑的程序）
total = 0
count = 0
maxss = None
minss = None
while True:
    s = input("请输入成绩（输入 q 退出）：")
    if s == "q":
        break
    try:
        score = int(s)
    except ValueError:
        print("输入的不是数字，请重新输入")
        continue
    total += score
    count += 1
    if maxss is None or score > maxss:
        maxss = score
    if minss is None or score < minss:
        minss = score
    if score >= 90:
        print("成绩等级：A")
    elif score >= 80:
        print("成绩等级：B")
    elif score >= 70:
        print("成绩等级：C")
    elif score >= 60:
        print("成绩等级：D")
    else:
        print("成绩等级：F")

try:
    total / count
except ZeroDivisionError:
    print("没有输入任何成绩，无法计算平均分")
    exit()
print("一共输入了 " , count , "个成绩")
print("总分是：" , total)
print("平均分是：" , total / count )
print("最高分是：" , maxss)
print("最低分是：" , minss)