# ========== 今天唯一的新概念：累加器 ==========
#
# 累加器就是"一个在循环外准备好、在循环里不断往上加"的变量：
#
#     total = 0                 ← 循环【外】：准备一个空盒子
#     while ...:
#         total += score        ← 循环【内】：每一轮往里放一点
#     print(total)              ← 循环【外】：最后看盒子里的总量
#
# 这个模式你以后会用一辈子：统计总和、计数、求和、累乘，全是它。
#
# ⚠️ 为什么 total = 0 必须写在【循环外】？
#    写在循环里面的话，每一轮都会把它重新清零，
#    最后盒子里只剩最后一次加的东西。你可以故意试试看。


