# ============================================================
# 知识卡
# ============================================================
#   创建：   d = {"数学": 85, "英语": 76}
#   取值：   d["数学"]           → 85
#   改/加：  d["数学"] = 90      → 改了
#            d["语文"] = 88      → 新增一个键
#   删除：   del d["英语"]
#
#   遍历所有键值对：   for k, v in d.items():
#   只要所有键：       d.keys()
#   只要所有值：       d.values()
#   判断键在不在：     if "数学" in d:
#   安全取值：         d.get("不存在的科目")   → 返回 None，不报错
#
#   ⚠️ 最大的坑：
#      d["不存在的键"]  → 【直接崩溃】（KeyError）
#      d.get("不存在的键") → 返回 None，安全
# ============================================================


scores = {}

print("=== 成绩册 5.0（字典版）===")
print("输入格式：科目 分数  （中间空格）")
print("例如：数学 85")
print("直接回车结束\n")

while True:
    line = input("输入：").strip()
    if line == "":
        break

    parts = line.split()          # 按空格切开，parts 是个列表

    if len(parts) != 2:
        print("格式不对，要写成「科目 分数」")
        continue

    subject = parts[0]
    try:
        score = float(parts[1])
    except ValueError:
        print("分数不是数字，重来")
        continue

    scores[subject] = score       # 存进字典

if len(scores) == 0:
    print("没有录入任何成绩")
    exit()
for k , v in scores.items():
    print(f"{k}：{v:.1f}")
avg = sum(scores.values()) / len(scores)
scores["平均分"] = avg
print(f"平均分：{avg:.2f}")
max_score = None
max_subject = None
for k, v in scores.items():
    if max_score is None or v > max_score:
        max_score = v
        max_subject = k
print(f"最高分：{max_score:.1f}（{max_subject}）")
want = input("想查哪个科目：")
if scores.get(want) is not None:
    print(f"{want}：{scores[want]:.1f}")
else:
    print("没录入这个科目")

