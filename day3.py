# ========== 先看这个：从 C 到 Python 的写法对照 ==========
#
#   C 语言：
#       if (score >= 60) {
#           printf("及格\n");
#       } else if (score >= 90) {
#           printf("优秀\n");
#       } else {
#           printf("不及格\n");
#       }
#
#   Python：
#       if score >= 90:
#           print("优秀")
#       elif score >= 60:
#           print("及格")
#       else:
#           print("不及格")
#
#   三个区别，每个都会让你踩坑：
#     1. 条件两边【没有括号】了
#     2. 行尾【必须有冒号 :】     ← 忘了必报 SyntaxError
#     3. 没有花括号，用【缩进】划分代码块
#        —— 在 Python 里缩进是语法的一部分，不是排版！缩进错了程序就跑不了
#
#   还有个新词：C 里写 else if，Python 里写 elif（少个空格，是连在一起的）


